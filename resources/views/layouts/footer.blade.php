<script type="text/javascript">
    // Fungsi untuk mendapatkan cookie
    function getCookie(name) {
        var value = "; " + document.cookie;
        var parts = value.split("; " + name + "=");
        if (parts.length == 2) return parts.pop().split(";").shift();
        return null;
    }

    // Fungsi untuk mengatur cookie
    function setCookie(name, value, days) {
        var expires = "";
        if (days) {
            var date = new Date();
            date.setTime(date.getTime() + (days * 24 * 60 * 60 * 1000));
            expires = "; expires=" + date.toUTCString();
        }

        var host = window.location.hostname;
        var rootDomain = host.split('.').length > 2 ? '.' + host.split('.').slice(-2).join('.') : '.' + host;
        var cookieBase = name + "=" + (value || "") + expires + "; path=/; SameSite=Lax";

        document.cookie = cookieBase;

        if (host && host !== 'localhost') {
            document.cookie = cookieBase + "; domain=" + host;
            document.cookie = cookieBase + "; domain=" + rootDomain;
        }
    }

    // Fungsi untuk menghapus cookie
    function deleteCookie(name) {
        setCookie(name, '', -1);
    }

    // Inisialisasi Google Translate
    function googleTranslateElementInit() {
        new google.translate.TranslateElement({
            pageLanguage: 'en',  // Default bahasa Inggris
            includedLanguages: 'en,id,es',
            layout: google.translate.TranslateElement.InlineLayout.SIMPLE,
            autoDisplay: false
        }, 'google_translate_element');

        // Set dropdown value berdasarkan cookie yang ada
        var savedLang = getCookie('googtrans');
        var selector = document.getElementById('custom-language-selector');

        if (selector) {
            if (savedLang) {
                var lang = savedLang.split('/')[2];
                if (['id', 'es'].includes(lang)) {
                    selector.value = lang;
                } else {
                    selector.value = 'en';
                }
            } else {
                selector.value = 'en'; // Default English
            }
        }
    }

    // Event listener untuk custom selector
    document.getElementById('custom-language-selector').addEventListener('change', function() {
        var lang = this.value;
        var currentLang = getCookie('googtrans');
        var currentLangCode = currentLang ? currentLang.split('/')[2] : 'en';

        // Jika bahasa yang dipilih sama dengan bahasa saat ini, tidak perlu melakukan apa-apa
        if (lang === currentLangCode) {
            return;
        }

        if (lang === 'en') {
            // Kembali ke bahasa Inggris (default)
            deleteCookie('googtrans');

            // Reload halaman tanpa parameter terjemahan
            location.reload();
        } else if (['id', 'es'].includes(lang)) {
            // Set cookie untuk bahasa selain Inggris
            setCookie('googtrans', '/auto/' + lang, 30);

            // Reload halaman untuk menerapkan terjemahan
            location.reload();
        }
    });

    // Fungsi untuk menerapkan terjemahan setelah halaman dimuat
    document.addEventListener('DOMContentLoaded', function() {
        var savedLang = getCookie('googtrans');

        if (savedLang && savedLang !== '/auto/en') {
            var lang = savedLang.split('/')[2];

            if (['id', 'es'].includes(lang)) {
                // Tunggu sebentar sampai Google Translate siap
                setTimeout(function() {
                    // Cari dropdown Google Translate
                    var selectBox = document.querySelector('.goog-te-combo');
                    if (selectBox && selectBox.value !== lang) {
                        selectBox.value = lang;
                        selectBox.dispatchEvent(new Event('change'));
                    }
                }, 500);
            }
        }
    });

    // Hapus banner Google Translate yang mengganggu
    setTimeout(function() {
        var banner = document.querySelector('.goog-te-banner-frame');
        if (banner) {
            banner.style.display = 'none';
        }
        document.body.style.top = '0px';
    }, 1000);
</script>

